CREATE OR REPLACE VIEW TICKETSUMMARY AS
SELECT MAX(T.ID) AS ID, MAX(T.CREATEDATE) AS CREATEDATE, T.CREATEUSER, MAX(T.MODIFYDATE) AS MODIFYDATE, T.MODIFYUSER,
R.EVENT_ID, E.`DATE`, E.SEASON_ID, H.VENUE_ID, T.PRICECATEGORY_ID, T.SEATCATEGORY_ID, SUM(T.AMOUNT) AS TICKETS,
C.CAPACITY AS CAPACITY,
SUM(T.AMOUNT * T.PRICE_AMOUNT) AS TOTAL_AMOUNT, T.PRICE_CURRENCY AS TOTAL_CURRENCY
FROM RESERVATIONTICKET T
  JOIN RESERVATION R ON T.RESERVATION_ID = R.ID
  JOIN EVENT E ON R.EVENT_ID = E.ID
  JOIN HALL H ON E.HALL_ID = H.ID
  JOIN HALLCAPACITY C ON E.HALL_ID = C.HALL_ID AND T.SEATCATEGORY_ID = C.SEATCATEGORY_ID
WHERE R.STATUS != 'CANCELED'
GROUP BY R.EVENT_ID, PRICECATEGORY_ID, SEATCATEGORY_ID;

UPDATE RESERVATIONTICKET SET SEATCATEGORY_ID = 1 WHERE SEATCATEGORY_ID IS NULL;