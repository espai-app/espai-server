--
-- PRODUCTIONTYPE TABLE
--
CREATE TABLE PRODUCTIONTYPE (
  ID BIGINT PRIMARY KEY NOT NULL,
  CREATEUSER VARCHAR(50) DEFAULT NULL,
  CREATEDATE DATETIME DEFAULT NULL,
  MODIFYUSER VARCHAR(50) DEFAULT NULL,
  MODIFYDATE DATETIME DEFAULT NULL,
  NAME VARCHAR(50) DEFAULT NULL,
  ICON VARCHAR(50) DEFAULT NULL,
  COLOR VARCHAR(10) DEFAULT NULL,
  INACTIVE TINYINT DEFAULT NULL
);
CREATE SEQUENCE productionType_id_seq START WITH 1 INCREMENT BY 1;




--
-- PRODUCTIONMETAFIELD TABLE
--
CREATE TABLE PRODUCTIONMETAFIELD (
  ID BIGINT PRIMARY KEY NOT NULL,
  CREATEUSER VARCHAR(50) DEFAULT NULL,
  CREATEDATE DATETIME DEFAULT NULL,
  MODIFYUSER VARCHAR(50) DEFAULT NULL,
  MODIFYDATE DATETIME DEFAULT NULL,
  PRODUCTIONTYPE_ID BIGINT DEFAULT NULL,
  NAME VARCHAR(50) DEFAULT NULL,
  LABEL VARCHAR(50) DEFAULT NULL,
  POSITION INT DEFAULT NULL,
  FIELDTYPE VARCHAR(50) DEFAULT 'UNSET',
  MULTIVALUED TINYINT DEFAULT NULL,
  PRESETS TEXT DEFAULT NULL,
  ATTACHMENTTYPE VARCHAR(50) DEFAULT 'UNSET',
  INDEXED TINYINT DEFAULT NULL,
  FACET TINYINT DEFAULT NULL
);
CREATE SEQUENCE productionMetaField_id_seq START WITH 1 INCREMENT BY 1;


CREATE INDEX IX_PRODUCTIONMETAFIELD_PRODUCTIONTYPE ON PRODUCTIONMETAFIELD(PRODUCTIONTYPE_ID);


CREATE TABLE PRODUCTIONMETAVALUE (
  ID BIGINT PRIMARY KEY NOT NULL,
  CREATEUSER VARCHAR(50) DEFAULT NULL,
  CREATEDATE DATETIME DEFAULT NULL,
  MODIFYUSER VARCHAR(50) DEFAULT NULL,
  MODIFYDATE DATETIME DEFAULT NULL,
  PRODUCTION_ID BIGINT DEFAULT NULL,
  PRODUCTIONMETAFIELD_ID BIGINT DEFAULT NULL,
  POSITION INT DEFAULT NULL,
  ROLENAME VARCHAR(200) DEFAULT NULL,
  VALUE TEXT DEFAULT NULL
);
CREATE SEQUENCE productionMetaValue_id_seq START WITH 1 INCREMENT BY 1;


CREATE INDEX IX_PRODUCTIONMETAVALUE_PRODUCTION ON PRODUCTIONMETAVALUE(PRODUCTION_ID);
CREATE INDEX IX_PRODUCTIONMETAVALUE_PRODUCTIONMETAFIELD ON PRODUCTIONMETAVALUE(PRODUCTIONMETAFIELD_ID);

